if (-not $py) {
    foreach ($c in @('D:\environment\PYTHON\python.exe',
                     'C:\Python311\python.exe',
                     'C:\Python312\python.exe',
                     'C:\Python313\python.exe')) {
        if (Test-Path -LiteralPath $c) { $py = $c; break }
    }
}
if (-not $py) { $py = 'python' }
if (-not $Project) { $Project = Split-Path -Parent $MyInvocation.MyCommand.Path }
$cfgPath = Join-Path $Project 'build-skeleton.json'
if (-not (Test-Path -LiteralPath $cfgPath)) { throw "build_skeleton: $cfgPath missing (run wizard first)" }
$cfg = Get-Content -LiteralPath $cfgPath -Raw | ConvertFrom-Json

$REPO = $cfg.repo_path
$genDir = Join-Path $Project 'gen'
$outDir = $Out
if (-not $outDir) { $outDir = $cfg.out_dir }
New-Item -ItemType Directory -Force $genDir, $outDir | Out-Null

$appName = $cfg.app_name          # exe 名 (无扩展名)
$display = $cfg.display_name
$serialName = $cfg.serial
$lite = if ($cfg.lite -eq $true) { '-DPROT_LITE_GUI' } else { '' }

# ---- vcvars (同 build.ps1 探测) ----
