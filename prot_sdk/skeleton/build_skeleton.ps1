# build_skeleton.ps1 — 保护壳工程构建流水线 (prot_sdk/skeleton 派生)
# 由 prot_wizard.py 生成到工程目录后运行, 或手工调用:
#   powershell -File build_skeleton.ps1 -Project <dir> [-Out <dir>] [-VcVars <path>]
# 读取 <Project>\build-skeleton.json: app_name/display_name/serial/key_mode/
#   key_pub_blob(可选)/lite/out_dir。
# 依赖: 仓库 tools/ src/ include/ 与本骨架工程 (复制自 prot_sdk/skeleton)。
param(
    [string]$Project = $null,
    [string]$Out = $null,
    [string]$Composition = ''      # 阶段4: 拼装图名 (compositions/<name>.json)
)
$ErrorActionPreference = 'Stop'
# python 探测: 环境变量优先, 其次常见安装路径, 最后 PATH (避开 WindowsApps 占位)
$py = $env:PROT_SDK_PYTHON
if (-not $py) {
    foreach ($c in @('D:\environment\PYTHON\python.exe',
                     'C:\Python311\python.exe',
                     'C:\Python312\python.exe',
                     'C:\Python313\python.exe')) {
        if (Test-Path -LiteralPath $c) { $py = $c; break }
    }
}
if (-not $py) { $py = 'python' }
if (-not $Project) { $Project = Split-Path -Parent $MyInvocation.MyCommand.Path }
$cfgPath = Join-Path $Project 'build-skeleton.json'
if (-not (Test-Path -LiteralPath $cfgPath)) { throw "build_skeleton: $cfgPath missing (run wizard first)" }
$cfg = Get-Content -LiteralPath $cfgPath -Raw | ConvertFrom-Json

$REPO = $cfg.repo_path
$genDir = Join-Path $Project 'gen'
$outDir = $Out
if (-not $outDir) { $outDir = $cfg.out_dir }
New-Item -ItemType Directory -Force $genDir, $outDir | Out-Null

$appName = $cfg.app_name          # exe 名 (无扩展名)
$display = $cfg.display_name
$serialName = $cfg.serial
$lite = if ($cfg.lite -eq $true) { '-DPROT_LITE_GUI' } else { '' }

# ---- vcvars (同 build.ps1 探测) ----
$vcvars = $null
if (Test-Path -LiteralPath "D:\environment\VS2022BuildTools\VC\Auxiliary\Build\vcvars64.bat") {
    $vcvars = "D:\environment\VS2022BuildTools\VC\Auxiliary\Build\vcvars64.bat"
} else {
    $cands = @(
        'C:\Program Files\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat',
        'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat',
        'C:\Program Files (x86)\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars64.bat',
        'C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars64.bat',
        'C:\Program Files\Microsoft Visual Studio\2022\Professional\VC\Auxiliary\Build\vcvars64.bat')
    foreach ($c in $cands) { if (Test-Path -LiteralPath $c) { $vcvars = $c; break } }
}
if (-not $vcvars) { throw 'build_skeleton: vcvars64.bat not found' }
Write-Host "build_skeleton: vcvars = $vcvars"

# ---- 1. 序列号期望 (vm_build.json) ----
$vb = Join-Path $Project 'vm_build.json'
if (-not (Test-Path -LiteralPath $vb)) {
    Set-Content -LiteralPath $vb -Value "{`"serial`":`"$serialName`",`"machine_id`":0}" -Encoding ascii
}
& $py "$REPO\tools\vmenc.py" genserial --json $vb
if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: genserial' }
$jbExpect = Get-Content -LiteralPath $vb -Raw | ConvertFrom-Json
$expectC = @(
    '/* generated by build_skeleton.ps1 from vm_build.json - do not edit */',
    "#include <stdint.h>",
    'const uint64_t g_prot_expect_default[2] = {',
    "  $($jbExpect.expect1), $($jbExpect.expect2),",
    '};')
Set-Content -LiteralPath (Join-Path $genDir 'expect_default.c') -Value $expectC -Encoding ascii

# ---- 2. 公钥: key_mode = new(临时钥对) | pub(引用 pub-blob.c) ----
if ($cfg.key_mode -eq 'pub') {
    Copy-Item -LiteralPath $cfg.key_pub_blob -Destination (Join-Path $genDir 'license_pubkey.c') -Force
    # 无私钥: smoke 走"授权门默认放行"路径 (license 由正式签发体系)
} else {
    $privJson = Join-Path $genDir 'license_priv.json'
    if (Test-Path -LiteralPath $privJson) {
        & $py "$REPO\tools\vmenc.py" keygen --key-out $privJson --blob-out (Join-Path $genDir 'license_pubkey.c')
    } else {
        & $py "$REPO\tools\vmenc.py" keygen --key-out $privJson --blob-out (Join-Path $genDir 'license_pubkey.c')
    }
    if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: keygen' }
}

# ---- 3. 授权 VM (4 个 vasm 已复制进工程) ----
foreach ($v in @('hash', 'mix', 'verify', 'gate')) {
    & $py "$REPO\tools\vmenc.py" assemble (Join-Path $Project "license_$v.vasm") $vb `
        (Join-Path $genDir "vm_${v}_blob.c") (Join-Path $genDir "vm_${v}_blob.h") `
        --name "g_vm_${v}_image" --bin-out (Join-Path $genDir "vm_${v}_blob.bin") --bin-name $v
    if ($LASTEXITCODE -ne 0) { throw "build_skeleton FAILED: assemble $v" }
}
# ---- 3b. A2 phase2: @vmcalc 业务函数自动 VM 化 (扫描/翻译/改名/桩) ----
$vmcalcDef = ''
$vmcalcSrcs = @(Get-ChildItem -LiteralPath $Project -Filter '*.c' -File |
               Where-Object { $_.Name -ne 'app_main.c' -and $_.Name -ne 'pub-blob.c' } |
               ForEach-Object { $_.FullName })
if ($vmcalcSrcs.Count -gt 0) {
    & $py "$REPO\tools\vmcalc_build.py" --src $vmcalcSrcs --gen $genDir --json $vb --vmenc "$REPO\tools\vmenc.py"
    if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: vmcalc_build' }
    if (Test-Path -LiteralPath (Join-Path $genDir 'vmcalc_stubs.c')) {
        $vmcalcDef = '-DPROT_HAS_VMCALC'
        Write-Host 'build_skeleton: @vmcalc 业务函数已 VM 化'
    }
}

# blob 签名: new 模式构建期自签 (smoke 可全过); pub 模式产出"待签发"blob,
# 发布时由签发方 (服务器私钥) 补签: vmenc.py pack --sign <priv.json> ...
# 业务 VM bin 附加进同一 blob (修改后重新 pack)
$packBins = @((Join-Path $genDir 'vm_hash_blob.bin'), (Join-Path $genDir 'vm_mix_blob.bin'),
              (Join-Path $genDir 'vm_verify_blob.bin'), (Join-Path $genDir 'vm_gate_blob.bin'))
if (Test-Path -LiteralPath (Join-Path $genDir 'vmcalc_stubs.c')) {
    $vmcalcBins = Get-ChildItem -LiteralPath $genDir -Filter 'vmcalc_*.bin' -File |
                  ForEach-Object { $_.FullName }
    $packBins += $vmcalcBins
}
if ($cfg.key_mode -eq 'new') {
    & $py "$REPO\tools\vmenc.py" pack --sign (Join-Path $genDir 'license_priv.json') `
        --out (Join-Path $outDir 'vm.blob') $packBins
} else {
    & $py "$REPO\tools\vmenc.py" pack --out (Join-Path $outDir 'vm.blob') $packBins
    Write-Host 'build_skeleton: vm.blob 未签名 (pub 模式) - 发布前由签发方补签:'
    Write-Host "  vmenc.py pack --sign <server-priv.json> --out vm.blob $($packBins | ForEach-Object { (Split-Path $_ -Leaf) })"
}
if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: pack' }

# ---- 4. 字符串 + 间接表 + expect ----
& $py "$REPO\tools\strgen.py" (Join-Path $Project 'strings.txt') (Join-Path $genDir 'strings.c')
if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: strgen' }
& $py "$REPO\tools\indirect.py" --out (Join-Path $genDir 'indirect_table.c')
if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: indirect' }

# ---- 5. 编译 + 链接 (工程内除 app_main.c 外的全部业务 .c 自动纳入) ----
$busSrcs = ((Get-ChildItem -LiteralPath $Project -Filter '*.c' -File |
             Where-Object { $_.Name -ne 'app_main.c' -and $_.Name -ne 'pub-blob.c' }) |
            ForEach-Object { $_.FullName }) -join ' '
$srcBase = "$REPO\src"
# 显示名不参与编译宏 (空格会破坏 -D); 显示名改在工程 strings.txt 的 BANNER.
$defines = "-DAPP_EXE_NAME=`"$appName`" $lite $vmcalcDef"
$vmcalcObj = if ($vmcalcDef) { "`"$genDir\vmcalc_stubs.c`"" } else { '' }
if ($cfg.key_mode -eq 'pub') {
    $signStep = ''  # 无本地私钥, 构建期自签 license 不可行 -> smoke 走无 license 路径
} else {
    $signStep = '& $py "$REPO\tools\vmenc.py" sign --key ' + (Join-Path $genDir 'license_priv.json') +
                " --json $vb --out " + (Join-Path $outDir 'license.txt')
}

# ---- 5a. 组合 (阶段4): 由 tools/compose.py 决定参与编译的 src/*.c + 生成
#          prot_modconfig.h (app_main.c 据此条件编译)。
#          默认 full = 全模块 (等价于改造前硬编码行为)。
#          源文件顺序由 compose.py 的 SOURCE_ORDER 固定 —— 顺序影响 .text
#          布局, 不可重排 (见该常量注释)。
$compName = if ($Composition) { $Composition } else { 'full' }
$compSrcList = Join-Path $genDir 'composition_srcs.txt'
& $py "$REPO\tools\compose.py" $compName `
      --header-out (Join-Path $genDir 'prot_modconfig.h') `
      --sources-out $compSrcList
if ($LASTEXITCODE -ne 0) { throw "build_skeleton FAILED: compose.py ($compName)" }
$compSrcs = @(Get-Content -LiteralPath $compSrcList | Where-Object { $_.Trim() } |
              ForEach-Object { Join-Path $REPO ($_.Trim() -replace '/', '\') })
if ($compSrcs.Count -eq 0) { throw "build_skeleton FAILED: composition '$compName' 无源文件" }
$compSrcJoined = ($compSrcs | ForEach-Object { "`"$_`"" }) -join ' '
Write-Host ("build_skeleton: composition '{0}' — {1} 源文件" -f $compName, $compSrcs.Count)

<# 实际执行 (单独 cmd /c 以获得 vcvars 环境) #>
$clCmd = "cl /nologo /O2 /W4 /WX /std:c11 /utf-8 /I `"$REPO\include`" /I `"$genDir`" $defines /Fe:`"$outDir\$appName.exe`" " +
    "$compSrcJoined " +
    "`"$Project\app_main.c`" $busSrcs $vmcalcObj " +
    "`"$genDir\strings.c`" `"$genDir\license_pubkey.c`" `"$genDir\indirect_table.c`" `"$genDir\expect_default.c`" " +
    "/link /SUBSYSTEM:CONSOLE bcrypt.lib winhttp.lib advapi32.lib /MAP:`"$outDir\$appName.map`""
cmd /c "`"$vcvars`" >nul 2>&1 && $clCmd" 2>&1 | Tee-Object -FilePath (Join-Path $outDir 'cl_log.txt') | Out-Host
if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: cl (log: cl_log.txt)' }

# ---- 6. selfcrypt + hashpatch (与 demo 同链; 掩码经 --mask-out 落 outDir) ----
#      阶段4 (组合): 组合排除 integrity/antidebug 时, 其加密目标不在 .map 中
#      -> selfcrypt_proto 跳过并报告; 仅 full 组合用 --require-all 保持严格。
$scArgs = @()
if ($compName -eq 'full') { $scArgs += '--require-all' }
& $py "$REPO\tools\selfcrypt_proto.py" "$outDir\$appName.exe" "$outDir\$appName.map" "--mask-out" "$outDir\selfcrypt_mask.txt" @scArgs
if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: selfcrypt_proto' }
$maskArgs = @()
if (Test-Path -LiteralPath "$outDir\selfcrypt_mask.txt") {
    foreach ($ln in (Get-Content -LiteralPath "$outDir\selfcrypt_mask.txt")) { $maskArgs += '--mask', $ln.Trim() }
}
#      阶段4 (组合): .protcrc 段由 src/integrity.c 定义 —— 组合不含 integrity
#      时该段不存在, hashpatch 无目标可写。此时跳过并报告 (该组合本就不含
#      完整性校验, 没有 CRC 需要烧录)。属预期而非缺陷。
$hasIntegrity = $compSrcs -match 'integrity\.c$'
if ($hasIntegrity) {
    & $py "$REPO\tools\hashpatch.py" "$outDir\$appName.exe" @maskArgs
    if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: hashpatch' }
} else {
    Write-Host 'build_skeleton: hashpatch SKIPPED (组合不含 integrity, 无 .protcrc 段)'
}

# ---- 6.5 数字签名 (WDAC 环境下新 exe 需签名放行; pfx 与 demo 共用) ----
$pfx = Join-Path $REPO 'build\keys\codesign.pfx'
if (Test-Path -LiteralPath $pfx) {
    $signtool = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin" `
        -Recurse -Filter signtool.exe -ErrorAction SilentlyContinue |
        Sort-Object FullName -Descending | Select-Object -First 1
    if ($signtool) {
        $pass = ''
        if ($env:SIGN_PASSWORD) { $pass = "/p $env:SIGN_PASSWORD" }
        elseif (Test-Path -LiteralPath "$REPO\build\keys\sign.pass") {
            $pass = '/p ' + (Get-Content -LiteralPath "$REPO\build\keys\sign.pass" -Raw).Trim()
        }
        cmd /c "`"$($signtool.FullName)`" sign /fd SHA256 /f `"$pfx`" $pass /t http://timestamp.digicert.com `"$outDir\$appName.exe`""
        if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: signtool sign' }
        Write-Host "build_skeleton: signed $appName.exe"
    }
} else {
    Write-Host 'build_skeleton: codesign.pfx absent - skip signing'
}

# ---- 7. 自签 license (key_mode=new) + smoke (按退出码判定) ----
if ($cfg.key_mode -eq 'new') {
    Invoke-Expression $signStep
    if ($LASTEXITCODE -ne 0) { throw 'build_skeleton FAILED: sign' }
}
$set = "$serialName`n"
$inFile = Join-Path $outDir 'smoke_stdin.txt'
Set-Content -LiteralPath $inFile -Value $serialName -Encoding ascii
$sOut = Join-Path $outDir 'smoke_out.log'
Remove-Item -LiteralPath $sOut -ErrorAction SilentlyContinue
$p = Start-Process -FilePath "$outDir\$appName.exe" `
    -ArgumentList '--license-file', "$outDir\license.txt", '--vm-blob', "$outDir\vm.blob", '--wait-after', '6000' `
    -RedirectStandardInput $inFile -RedirectStandardOutput $sOut -PassThru
Start-Sleep -Seconds 9
if (-not $p.HasExited) { $p.WaitForExit(15000) | Out-Null }
if (-not $p.HasExited) { Stop-Process -Id $p.Id -Force; $smokeOk = $false } else { $smokeOk = $true }
$sLines = Get-Content -LiteralPath $sOut -ErrorAction SilentlyContinue
Write-Host "build_skeleton: smoke output: $($sLines -join ' | ')"
if ($cfg.key_mode -ne 'new') {
    # pub 模式: blob 待签发, 运行到"装载失败"属预期 (产品交付前由服务器补签)
    Write-Host 'build_skeleton: pub 模式 smoke 预期到 VM 装载点 (blob 待签发) - 构建完成' -ForegroundColor Green
} elseif (($sLines -join ' ') -match 'business:') {
    # new 模式: 授权门通过 + 业务 stub 已执行 = 全链路通
    Write-Host 'build_skeleton: smoke PASS (license ok + business executed)' -ForegroundColor Green
} else {
    Write-Host 'build_skeleton: smoke FAILED (manual verify needed)' -ForegroundColor Yellow
}
Write-Host "build_skeleton: DONE -> $outDir"