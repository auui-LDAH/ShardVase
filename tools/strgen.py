#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tools/strgen.py — 字符串加密生成器  (Lane C)

Reads a manifest of `NAME|text` lines (UTF-8) and emits a C file that
holds every string as a per-string 64-bit key + rolling-keystream cipher
text, plus a `prot_str_get` implementation that decrypts everything on
first use.

Algorithms and CLI are defined in docs/CONTRACT.md (§3, §8).

CLI:
    python tools/strgen.py demo/strings.txt demo/gen/strings.c
"""

import os
import random
import struct
import sys

M64 = (1 << 64) - 1

KS_MUL = 0x5851F42D4C957F2D
KS_ADD = 0x14057B7EF767814F

BUF_SIZE = 128  # per-string plaintext buffer (incl. trailing NUL)

# Must exactly match the prot_str_id enum order in include/protect/strcrypt.h
EXPECTED_ORDER = [
    'BANNER',
    'PROMPT_SERIAL',
    'MSG_OK',
    'MSG_FAIL',
    'MSG_DBG',
    'MSG_TAMPER',
    'MSG_HWID',
    'MSG_BLOB',
]


class StrgenError(Exception):
    pass


def encrypt(plain, seed):
    """Encrypt UTF-8 bytes with the CONTRACT §3 rolling keystream."""
    k = seed
    out = bytearray()
    for b in plain:
        k = (k * KS_MUL + KS_ADD) & M64
        out.append(b ^ ((k >> 56) & 0xFF))
    return bytes(out)


def parse_manifest(path):
    """
    Parse `NAME|text` lines. Blank lines are ignored.
    Names must appear exactly once, in the prot_str_id enum order.
    Returns list of (name, utf8_bytes).
    """
    with open(path, 'r', encoding='utf-8') as f:
        raw = f.read()

    entries = []
    for lineno, line in enumerate(raw.split('\n'), 1):
        line = line.rstrip('\r').strip()
        if not line:
            continue
        if '|' not in line:
            raise StrgenError('%s line %d: expected NAME|text' % (path, lineno))
        name, _, text = line.partition('|')
        if '|' in text:
            raise StrgenError('%s line %d: text must not contain "|"' % (path, lineno))
        name = name.strip()
        if not name:
            raise StrgenError('%s line %d: empty NAME' % (path, lineno))
        entries.append((name, text))

    names = [n for n, _ in entries]
    if names != EXPECTED_ORDER:
        raise StrgenError(
            '%s: NAME order/count must exactly match prot_str_id: %s (got %s)'
            % (path, EXPECTED_ORDER, names))

    out = []
    for name, text in entries:
        blob = text.encode('utf-8')
        if len(blob) >= BUF_SIZE:
            raise StrgenError(
                '%s: string %s is %d UTF-8 bytes (max %d)'
                % (path, name, len(blob), BUF_SIZE - 1))
        out.append((name, blob))
    return out


def format_bytes(data, per_line=12):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append('        ' + ', '.join('0x%02x' % b for b in chunk) + ',')
    return '\n'.join(lines)


def generate_c(entries):
    """entries: list of (name, utf8_bytes). Returns generated C source."""
    count = len(entries)
    blocks = []
    struct_rows = []
    enc_names = []
    for i, (_name, blob) in enumerate(entries):
        seed = random.getrandbits(64)
        cipher = encrypt(blob, seed)
        enc_name = 's_enc%d' % i
        enc_names.append(enc_name)
        blocks.append(
            'static const uint8_t %s[] = {\n%s\n    };\n' % (
                enc_name, format_bytes(cipher)))
        struct_rows.append(
            '    { %du, 0x%016xULL, %s },' % (len(blob), seed, enc_name))

    rows = '\n'.join(struct_rows)
    enc_decls = '\n'.join(blocks)

    src = (
        '/* generated by tools/strgen.py \u2014 do not edit */\n'
        '#include "protect/strcrypt.h"\n'
        '\n'
        'typedef struct prot_enc_str {\n'
        '    uint32_t len;\n'
        '    uint64_t key;\n'
        '    const uint8_t* enc;\n'
        '} prot_enc_str;\n'
        '\n'
        '%s\n'
        '\n'
        'static const prot_enc_str s_strs[] = {\n'
        '%s\n'
        '};\n'
        '\n'
        'static char s_bufs[PROT_STR_COUNT][%d];\n'
        'static int s_ready;\n'
        '\n'
        'const char* prot_str_get(prot_str_id id) {\n'
        '    if ((int)id < 0 || (int)id >= PROT_STR_COUNT)\n'
        '        return NULL;\n'
        '    if (!s_ready) {\n'
        '        for (int i = 0; i < PROT_STR_COUNT; ++i)\n'
        '            prot_str_decrypt(s_strs[i].enc, s_strs[i].len, s_strs[i].key, s_bufs[i]);\n'
        '        s_ready = 1;\n'
        '    }\n'
        '    return s_bufs[id];\n'
        '}\n'
    ) % (enc_decls, rows, BUF_SIZE)
    return src


def main(argv=None):
    import argparse
    parser = argparse.ArgumentParser(
        prog='strgen.py',
        description='string encryptor generator (Lane C)')
    parser.add_argument('manifest', help='demo/strings.txt (NAME|text lines)')
    parser.add_argument('out_c', help='output demo/gen/strings.c')
    args = parser.parse_args(argv)

    try:
        entries = parse_manifest(args.manifest)
        src = generate_c(entries)
        parent = os.path.dirname(os.path.abspath(args.out_c))
        if parent and not os.path.isdir(parent):
            os.makedirs(parent, exist_ok=True)
        with open(args.out_c, 'w', encoding='utf-8', newline='\n') as f:
            f.write(src)
        print('strgen: wrote %d encrypted strings to %s' % (len(entries), args.out_c))
    except StrgenError as e:
        print('strgen: error: %s' % e, file=sys.stderr)
        return 1
    except (OSError, UnicodeError) as e:
        print('strgen: error: %s' % e, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
