#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tools/indirect.py — 函数级间接化生成器 (N4)

从确定性种子派生宿主函数指针表的槽位置换 (复用 CONTRACT §3 的 xorshift64
流 + Fisher-Yates, 与 tools/vmenc.py 同构), 生成 demo/gen/indirect_table.c:

  * 静态表 s_fn[] 按**规范顺序**存函数指针 (与 vm.c g_routes 同构);
  * 静态表 s_perm[fn_id] = 槽位 (运行期取表下标);
  * 调用点 prot_indirect_resolve(fn_id) 只做一次查表, 无直接 call。

种子注入 (-SeedsFile, RELEASE I3 可复现构建): 同种子两次构建字节一致。

CLI:
    python tools/indirect.py --out demo/gen/indirect_table.c [--seed 0x..]
"""

import argparse
import os
import sys

M64 = (1 << 64) - 1


def xorshift64(x):
    x &= M64
    x ^= (x << 13) & M64
    x ^= x >> 7
    x ^= (x << 17) & M64
    return x & M64


def derive(seed, count):
    """从种子派生槽位置换 perm (fn_id -> 表下标), Fisher-Yates。"""
    x = seed & M64
    pool = list(range(count))
    for i in range(count - 1, 0, -1):
        x = xorshift64(x)
        j = x % (i + 1)
        pool[i], pool[j] = pool[j], pool[i]
    return pool


def generate_c(seed, names):
    """names: 函数名列表 (规范顺序, 与 indirect.h 枚举一致)。"""
    count = len(names)
    perm = derive(seed, count)

    # 表按反置换排列: s_fn[perm[fn_id]] == fn_{fn_id}
    # (resolve: s_fn[perm[fn_id]] 取回规范序函数, 同 vm.c dt[slot[canon]])
    inv = [0] * count
    for i, p in enumerate(perm):
        inv[p] = i

    # 跨编译单元可见的声明: load_and_verify_license 是 demo/main.c 的非 static
    # 函数 (demo_mem 类型未导出, 用 void* 声明, C 侧不做类型检查)。
    externs = []
    for name in names:
        if name == 'load_and_verify_license':
            externs.append(
                'extern int load_and_verify_license(const char*, void*);')
    externs_src = '\n'.join(externs)

    # s_fn 按反置换顺序填充: s_fn[inv[i]] = fn_i -> 表内顺序 = fn_{inv[0]}, fn_{inv[1]}, ...
    rows = []
    for i in range(count):
        name = names[inv[i]]
        rows.append('    (prot_indirect_fnp)%s,' % name)
    rows_src = '\n'.join(rows)

    perm_rows = []
    for i in range(0, count, 8):
        chunk = perm[i:i + 8]
        perm_rows.append('    ' + ', '.join('%du' % v for v in chunk) + ',')
    perm_src = '\n'.join(perm_rows)

    src = (
        '/* generated by tools/indirect.py \u2014 do not edit */\n'
        '#include "protect/indirect.h"\n'
        '#include "protect/vm.h"\n'
        '#include "protect/revoke.h"\n'
        '#include "protect/hostid.h"\n'
        '%s\n'
        '\n'
        '/* 规范顺序函数指针表 (N4: 槽位随机化, 静态无直接 call)。\n'
        ' * 统一存 prot_indirect_fnp (void(*)(void)) 泛型指针,\n'
        ' * 函数指针互转 MSVC 允许且 /W4 无告警 (无 C4152)。 */\n'
        'static const prot_indirect_fnp s_fn[PROT_INDIRECT_COUNT] = {\n'
        '%s\n'
        '};\n'
        '\n'
        '/* 槽位: fn_id -> 表下标 (构建期随机化, 每次构建不同) */\n'
        'static const uint8_t s_perm[PROT_INDIRECT_COUNT] = {\n'
        '%s\n'
        '};\n'
        '\n'
        'const prot_indirect_fnp* prot_indirect_table(void) { return s_fn; }\n'
        'const uint8_t* prot_indirect_perm(void) { return s_perm; }\n'
    ) % (externs_src, rows_src, perm_src)
    return src, perm


def main(argv=None):
    import argparse
    parser = argparse.ArgumentParser(
        prog='indirect.py',
        description='function indirection table generator (N4)')
    parser.add_argument('--out', dest='out', required=True,
                        help='output demo/gen/indirect_table.c')
    parser.add_argument('--seed', dest='seed', type=lambda s: int(s, 0),
                        default=None,
                        help='deterministic seed (hex/dec; default random) '
                             '- RELEASE I3 reproducible builds')
    args = parser.parse_args(argv)

    seed = args.seed if args.seed is not None else __import__('random').getrandbits(64)
    try:
        names = _fn_order_from_header()
        src, perm = generate_c(seed, names)
        parent = os.path.dirname(os.path.abspath(args.out))
        if parent and not os.path.isdir(parent):
            os.makedirs(parent, exist_ok=True)
        with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
            f.write(src)
        print('indirect: wrote %d function slots to %s (seed=0x%016x)'
              % (len(names), args.out, seed))
        print('indirect: perm=%s' % perm)
    except (OSError, ValueError) as e:
        print('indirect: error: %s' % e, file=sys.stderr)
        return 1
    return 0


# 枚举后缀 -> 实际函数符号 (C 编译单元可见名)
_FN_SYMBOLS = {
    'VM_RUN': 'prot_vm_run',
    'LICENSE': 'load_and_verify_license',
    'REVOKE': 'prot_revoke_check',
    'HOSTID': 'prot_hostid_get',
}


def _fn_order_from_header():
    """从 include/protect/indirect.h 的 PROT_INDIRECT_ 枚举解析规范顺序。"""
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, '..', 'include', 'protect', 'indirect.h')
    with open(path, 'r', encoding='utf-8') as f:
        text = f.read()
    m = __import__('re').search(
        r'enum\s+prot_indirect_fn\s*\{(.*?)\}', text, __import__('re').S)
    if not m:
        raise ValueError('cannot parse prot_indirect_fn enum in indirect.h')
    names = []
    for suffix in __import__('re').findall(r'PROT_INDIRECT_([A-Z0-9_]+)', m.group(1)):
        if suffix == 'COUNT':
            continue
        sym = _FN_SYMBOLS.get(suffix)
        if sym is None:
            raise ValueError('unknown indirect fn suffix: %s' % suffix)
        names.append(sym)
    if not names:
        raise ValueError('empty prot_indirect_fn enum')
    return names


if __name__ == '__main__':
    sys.exit(main())
