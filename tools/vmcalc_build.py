# vmcalc_build.py — A2 二阶段: prot_sdk 业务函数自动 VM 化构建辅助
# 职责 (由 build_skeleton.ps1 调用):
#   1) 扫描工程 .c 中 "// @vmcalc" 标注的下一个函数
#   2) c2vasm 翻译 -> .vasm -> vmenc assemble -> .bin (bin 名 b_<fn>)
#   3) 源文件中原函数定义改名 <fn> -> <fn>_native (去 static), 保持调用点不变
#   4) 生成 gen/vmcalc_stubs.c (装载器 + 同名桩) 与 gen/vmcalc_interface.h
# 用法: python vmcalc_build.py --src <src list...> --gen <gen dir> --json <vm_build.json>
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = '// @vmcalc'


def find_marked_functions(path):
    """返回[(函数名, 起始行号, is_native)]: 含 // @vmcalc 的下一个函数定义.
    is_native: 定义已被改名 _native (状态残留)."""
    with open(path, encoding='utf-8') as f:
        lines = f.readlines()
    marked = []
    for i, ln in enumerate(lines):
        if MARK in ln:
            for j in range(i, min(i + 4, len(lines))):
                m = re.search(r'\b(uint32_t|uint64_t)\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(', lines[j])
                if m:
                    marked.append((m.group(2), j, m.group(2).endswith('_native')))
                    break
    return marked, lines


def unrename_native(lines, fn):
    """把 '<fn>_native(' 定义行还原为 '<fn>(' (状态修复用)."""
    orig = fn[:-len('_native')]
    pat = re.compile(r'\b(uint(?:32|64)_t)\s+%s_native\(' % re.escape(orig))
    for i, ln in enumerate(lines):
        if pat.search(ln):
            lines[i] = pat.sub(r'\1 %s(' % orig, ln)
            return i
    return -1


def rename_definition(lines, fn):
    """把定义 'static uint64_t fn(...' 或 'uint64_t fn(...' 改为 '<fn>_native'.
    只改定义行(签名行), 调用点不受影响 (函数名仍为 fn -> 链接到桩)."""
    pat = re.compile(r'(static\s+)?(uint(?:32|64)_t)\s+%s\s*\(' % re.escape(fn))
    for i, ln in enumerate(lines):
        if pat.search(ln):
            lines[i] = pat.sub(r'\2 %s_native(' % fn, ln)
            return i
    return -1


def translate_and_assemble(fn, src_text, gen_dir, vmenc, vmjson):
    sys.path.insert(0, HERE)
    from c2vasm import parse_function, compile_function
    vasm = compile_function(src_text)
    vasm_path = os.path.join(gen_dir, 'vmcalc_%s.vasm' % fn)
    with open(vasm_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(vasm)
    blob_c = os.path.join(gen_dir, 'vmcalc_%s_blob.c' % fn)
    blob_h = os.path.join(gen_dir, 'vmcalc_%s_blob.h' % fn)
    bin_out = os.path.join(gen_dir, 'vmcalc_%s.bin' % fn)
    r = subprocess.run(
        [sys.executable, vmenc, 'assemble', vasm_path, vmjson,
         blob_c, blob_h, '--name', 'g_vmcalc_%s' % fn,
         '--bin-out', bin_out, '--bin-name', 'b_%s' % fn],
        capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError('assemble %s failed: %s' % (fn, r.stderr[-300:]))
    return bin_out


def gen_stubs(gen_dir, fns, params_of):
    """生成 vmcalc_stubs.c + vmcalc_interface.h."""
    n = len(fns)
    names = ', '.join('"b_%s"' % f for f in fns)
    heads = []
    for f in fns:
        ps = params_of[f]
        heads.append('uint64_t %s(%s);' % (f, ', '.join('uint64_t %s' % p for p in ps)))
    c = """/* auto-generated by vmcalc_build.py (A2 phase2) — do not edit */
#include <string.h>
#include <stdint.h>
#include "protect/vm.h"
#include "protect/blob.h"

#define VMCALC_OUT_OFF 0x1000
static prot_vm_image g_vmcalc_imgs[%d];
static const char* const k_vmcalc_names[%d] = { %s };
static void* g_vmcalc_buf = NULL;

int prot_vmcalc_count(void) { return %d; }

int prot_vmcalc_load(const char* path)
{
    size_t sz = 0;
    if (path == NULL) return -1;
    if (prot_vm_blob_load(path, k_vmcalc_names, %d,
                          g_vmcalc_imgs, &g_vmcalc_buf, &sz) != PROT_OK)
        return -1;
    return 0;
}

%s
""" % (n, n, names, n, n, '\n'.join(heads))
    for f, ps in params_of.items():
        memcpys = '\n'.join(
            '    uint64_t v%d = %s; memcpy(frame + %d, &v%d, 8);' % (i, p, 8 * i, i)
            for i, p in enumerate(ps))
        c += """
uint64_t %s(%s)
{
    unsigned char frame[0x2000];
    uint64_t r = 0;
    if (g_vmcalc_buf == NULL) {
        /* 装载只应在 prot_vmcalc_load 成功之后 (业务前). 防御: 惰性拒 */
        return 0;
    }
    memset(frame, 0, sizeof(frame));
%s
    if (prot_vm_run(&g_vmcalc_imgs[%d], frame, sizeof(frame)) != PROT_OK)
        return 0;
    memcpy(&r, frame + VMCALC_OUT_OFF, 8);
    return r;
}
""" % (f, ', '.join('uint64_t %s' % p for p in ps),
       memcpys if ps else '    (void)0;',
       fns.index(f))
    with open(os.path.join(gen_dir, 'vmcalc_stubs.c'), 'w',
              encoding='utf-8', newline='\n') as fh:
        fh.write(c)
    h = """/* auto-generated by vmcalc_build.py (A2 phase2) — do not edit */
#ifndef VMCALC_INTERFACE_H
#define VMCALC_INTERFACE_H

#include <stdint.h>

int prot_vmcalc_count(void);
int prot_vmcalc_load(const char* path);
%s
#endif
""" % '\n'.join(heads)
    with open(os.path.join(gen_dir, 'vmcalc_interface.h'), 'w',
              encoding='utf-8', newline='\n') as fh:
        fh.write(h)


def ensure_include(src_path, gen_dir):
    """注入 #include "vmcalc_interface.h" (构建生成头), 幂等."""
    tag = '#include "vmcalc_interface.h"'
    with open(src_path, encoding='utf-8') as f:
        text = f.read()
    if tag in text:
        return
    with open(src_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('#include "vmcalc_interface.h"  /* auto by vmcalc_build (A2) */\n' + text)


def main():
    ap = argparse.ArgumentParser(description='A2 phase2: @vmcalc 自动 VM 化')
    ap.add_argument('--src', nargs='+', required=True, help='工程 .c 源文件')
    ap.add_argument('--gen', required=True, help='gen 目录')
    ap.add_argument('--json', required=True, help='vm_build.json')
    ap.add_argument('--vmenc', default=os.path.join(HERE, 'vmenc.py'),
                    help='vmenc.py 路径')
    args = ap.parse_args()
    os.makedirs(args.gen, exist_ok=True)

    fns = []
    params_of = {}
    stubs_exist = os.path.isfile(os.path.join(args.gen, 'vmcalc_stubs.c'))

    # 一致性修复: 存在 _native 残留 但 stubs 缺失 (重建/gen 被清) -> 还原原名
    if not stubs_exist:
        for src in args.src:
            marked, lines = find_marked_functions(src)
            for fn, lineno, native in marked:
                if native and unrename_native(lines, fn) >= 0:
                    with open(src, 'w', encoding='utf-8', newline='\n') as f:
                        f.writelines(lines)
                    print('vmcalc: restore %s' % fn)

    for src in args.src:
        marked, lines = find_marked_functions(src)
        for fn, lineno, native in marked:
            if native:
                continue  # 已 _native 且 stubs 存在 -> 幂等跳过
            src_text = ''.join(lines[lineno:])
            sys.path.insert(0, HERE)
            from c2vasm import parse_function
            name, params, _ = parse_function(src_text)
            fns.append(fn)
            params_of[fn] = params
            if rename_definition(lines, fn) < 0:
                raise RuntimeError('@vmcalc 函数定义未找到: %s' % fn)
            with open(src, 'w', encoding='utf-8', newline='\n') as f:
                f.writelines(lines)
            ensure_include(src, args.gen)
            translate_and_assemble(fn, src_text, args.gen, args.vmenc, args.json)
            print('vmcalc: %s -> %s (params=%s)' % (fn, os.path.basename(src), params))

    if fns:
        gen_stubs(args.gen, fns, params_of)
        print('vmcalc: %d functions, stubs+interface generated' % len(fns))
    else:
        print('vmcalc: no @vmcalc functions')
    return 0


if __name__ == '__main__':
    sys.exit(main())